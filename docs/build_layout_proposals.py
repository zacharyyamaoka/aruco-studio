def _app_glyphs() -> dict[str, str]:
    stroke, accent = 'stroke="currentColor"', "var(--accent)"
    out: dict[str, str] = {}
    kit = (REPO / "studio/packages/bam-ui/src/Glyph.tsx").read_text()
    for m in re.finditer(r'^\s+"?([\w-]+)"?:\s*`(.*)`,\s*$', kit, re.M):
        out[m.group(1)] = m.group(2).replace("${S}", stroke)
    ts = (WEB / "src/ui/icons.ts").read_text()
    for m in re.finditer(r'^\s+"?([\w-]+)"?:\s*`(.*)`,\s*$', ts, re.M):
        out[m.group(1)] = m.group(2).replace("${S}", stroke).replace("${A}", accent)
    tb = (WEB / "src/app/Toolbar.tsx").read_text()
    out["dimension"] = re.search(r"dimension: '(.*?)',", tb).group(1)
    sk = (WEB / "src/skins/skins.ts").read_text()
    out["skin"] = re.search(r"skin: `(.*?)`,", sk, re.S).group(1)
    top = (WEB / "src/app/TopBar.tsx").read_text()
    out["github"] = re.search(r"function GithubMark.*?(<path .*?/>)", top, re.S).group(1)
    cube = re.search(r"function BrandCube.*?<svg[^>]*>(.*?)</svg>", top, re.S).group(1)
    out["brand"] = cube.replace("strokeWidth", "stroke-width").replace("strokeLinejoin", "stroke-linejoin").strip()
    return out


def _lucide(name: str) -> str:
    src = (WEB / "node_modules/lucide-react/dist/esm/icons" / f"{name}.mjs").read_text()
    alias = re.search(r"export \{ default \} from '\./([\w-]+)\.mjs'", src)
    if alias:  # a renamed icon (circle-help is circle-question-mark now)
        return _lucide(alias.group(1))
    node = re.search(r"node:\s*\[(.*)\]\s*\};", src, re.S).group(1)
    els = []
    for tag, body in re.findall(r'\[\s*"(\w+)",\s*\{([^}]*)\}\s*\]', node):
        kv = [(k, v) for k, v in re.findall(r'(\w+):\s*"([^"]*)"', body) if k != "key"]
        els.append(f"<{tag} " + " ".join(f'{k}="{v}"' for k, v in kv) + "/>")
    assert els, f"lucide {name}: no shapes parsed"
    return "".join(els)


