def capture(force: bool) -> dict:
    facts_file = SHOTS / "capture.json"
    if facts_file.exists() and not force:
        return json.loads(facts_file.read_text())
    SRC.mkdir(parents=True, exist_ok=True)
    js = CAPTURE_JS % {
        "playwright": json.dumps(str(WEB / "node_modules" / "playwright")),
        "stages": json.dumps(STAGES),
        "today": json.dumps(TODAY),
        "shots": json.dumps(str(SHOTS)),
        "live": json.dumps(LIVE),
    }
    (SRC / "capture.cjs").write_text(js)
    subprocess.run(["node", str(SRC / "capture.cjs")], cwd=WEB, check=True, timeout=900)
    return json.loads(facts_file.read_text())


