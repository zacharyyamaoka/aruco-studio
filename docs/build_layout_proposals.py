def judgment(built: dict) -> tuple[str, str, list]:
    """The AI recommendation and its hinge, computed from the scores (never typed)."""
    vs = {vv["id"]: vv for vv in built["variants"]}
    meta = {v["id"]: v for v in VARIANTS}
    rank = sorted(vs, key=lambda i: (built["eligible"][i], built["totals"][i]), reverse=True)
    w0 = {r["id"]: r["weight"] for r in REQUIREMENTS}

    def tot(i, w):
        return sum(w[k] * vs[i]["scores"][k]["score"] / 5 for k in w)
    top, second = rank[0], rank[1]
    a = built["report"][top]["desk"]
    gap = built["totals"][top] - built["totals"][second]
    co = gap <= 3
    tied = [i for i in rank[1:] if abs(built["totals"][i] - built["totals"][second]) < 0.01]
    names = " and ".join(f"{meta[i]['ref']} (V{i[1:]})" for i in tied)
    why = (f"{meta[top]['ref']} (V{top[1:]}) leads at {built['totals'][top]:.0f}/100"
           + (f", within 3 points of {names} ({built['totals'][second]:.0f}): treat them as co-leaders. " if co else
              f", {gap:.0f} ahead of {names} ({built['totals'][second]:.0f}{' each' if len(tied) > 1 else ''}). ")
           + f"It has the calmest first screen measured ({a['controls']} controls, {a['chrome_pct']}% chrome; today 20 and 8.4%), "
           f"and it keeps Verify | Print a labelled pair top-right at both widths. Its cost is CAD familiarity "
           f"({vs[top]['scores']['fr4']['score']}/5), and the tools' names are hover-only. The lead is fragile: see the hinge.")
    # the smallest shift of weight from calm (fr2) to CAD familiarity (fr4) that changes the winner
    flip = None
    for k in range(1, w0["fr2"]):
        w = dict(w0, fr2=w0["fr2"] - k, fr4=w0["fr4"] + k)
        best = max((i for i in vs if built["eligible"][i]), key=lambda i: tot(i, w))
        if best != top:
            flip = (k, best, tot(best, w), tot(top, w))
            break
    if flip:
        k, best, tb, tt = flip
        hinge = (f"Calm against CAD familiarity. Move {k} points of weight from \u201ca calm first screen\u201d to \u201cfeels like the CAD it lives in\u201d "
                 f"and {meta[best]['ref']} (V{best[1:]}) overtakes, {tb:.0f} to {tt:.0f}. If the web Studio is mostly the way into the Fusion and "
                 f"Onshape add-ins, make that shift and take {meta[best]['ref']}. If it is mostly for visitors arriving from the landing page, keep "
                 f"{meta[top]['ref']}. Its known gap is the missing tool names; splicing in {meta['v4']['ref']}'s Search tools would close it.")
    else:
        hinge = f"No shift of weight from calm to CAD familiarity changes the winner; the hinge is the hard gates."
    return why, hinge, rank


