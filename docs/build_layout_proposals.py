def webp_uri(path: Path, quality: int = 100) -> str:
    """Lossless WebP: these captures are flat UI, so lossless is as small as
    lossy q80 and has none of its ringing (it striped the white plate)."""
    from PIL import Image
    im = Image.open(path)
    buf = io.BytesIO()
    (im if im.mode == "RGBA" else im.convert("RGB")).save(buf, "WEBP", lossless=True, quality=quality, method=6)
    return "data:image/webp;base64," + base64.b64encode(buf.getvalue()).decode()


