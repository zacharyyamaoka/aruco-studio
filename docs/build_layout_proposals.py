def inter(a: dict, b: dict) -> float:
    w = min(a["x"] + a["w"], b["x"] + b["w"]) - max(a["x"], b["x"])
    h = min(a["y"] + a["h"], b["y"] + b["h"]) - max(a["y"], b["y"])
    return max(0.0, w) * max(0.0, h)


def chrome_of(m: dict) -> tuple[list, list, dict | None]:
    leaves = [l for l in m["leaves"] if not l["pop"] and not l["nest"]]
    boxes = [b for b in m["boxes"] if not b["pop"] and b["box"] not in ("stage", "panel", "panel-img")]
    panel = next((b for b in m["boxes"] if b["box"] == "panel"), None)
    img = next((b for b in m["boxes"] if b["box"] == "panel-img"), None)
    # the measured panel must be where the panel is drawn (its image), or every gate is moot
    assert panel and img and inter(panel, img) >= panel["w"] * panel["h"] - 1, f"panel rect not inside its image: {panel} {img}"
    return leaves, boxes, panel


def area_frac(rects: list, W: float, H: float, cell: int = 4) -> float:
    on = set()
    for r in rects:
        for gx in range(max(0, int(r["x"] // cell)), min(int(W // cell), int((r["x"] + r["w"]) // cell) + 1)):
            for gy in range(max(0, int(r["y"] // cell)), min(int(H // cell), int((r["y"] + r["h"]) // cell) + 1)):
                on.add((gx, gy))
    return len(on) * cell * cell / (W * H)


def analyse(v: dict, M: dict, facts: dict) -> dict:
    """The hard gates and the numbers behind the scores, from the measured boxes only."""
    res: dict = {}
    for form, st in (("desk", "desk"), ("phone", "phone")):
        m = M[st]
        leaves, boxes, panel = chrome_of(m)
        W, H = m["W"], m["H"]
        overl = []
        for i, a in enumerate(leaves):
            for b in leaves[i + 1:]:
                if inter(a, b) > 1:
                    overl.append(f"{a['c']} × {b['c']}")
            if panel and inter(a, panel) > 1:
                overl.append(f"{a['c']} × the panel")
        for bx in boxes:
            if panel and inter(bx, panel) > 1:
                overl.append(f"{bx['box']} × the panel")
        out = [l["c"] for l in leaves if l["x"] < -0.5 or l["y"] < -0.5 or l["x"] + l["w"] > W + 0.5 or l["y"] + l["h"] > H + 0.5]
        trunc = [l["c"] for l in leaves if l["trunc"]]
        loose = [l for l in leaves if not any(inter(l, bx) >= l["w"] * l["h"] - 1 for bx in boxes)]
        area = area_frac(boxes + loose, W, H)
        seen = sorted({l["c"] for l in leaves})
        res[form] = {"overlaps": overl, "outside": out, "truncated": trunc, "controls": len(leaves),
                     "chrome_pct": round(100 * area, 1), "seen": seen}
    # reachability: the union over each width's states
    desk_states = [s for s in M if not s.startswith("phone")]
    reach_d = {l["c"] for s in desk_states for l in M[s]["leaves"]}
    reach_p = {l["c"] for s in M if s.startswith("phone") for l in M[s]["leaves"]}
    res["missing_desk"] = sorted(set(INVENTORY) - reach_d)
    res["missing_phone"] = sorted(set(INVENTORY) - reach_p)
    res["frequent_missing_desk"] = sorted(set(FREQUENT) - set(res["desk"]["seen"]))
    res["frequent_on_phone"] = sorted(set(FREQUENT) & set(res["phone"]["seen"]))
    # G1: Print top-right, Verify immediately to its left, same row, nothing right of Print in that row
    leaves, _, _ = chrome_of(M["desk"])
    W = M["desk"]["W"]
    ver = next((l for l in leaves if l["c"] == "verify"), None)
    pri = next((l for l in leaves if l["c"] == "print"), None)
    g1, why = False, "Verify or Print is not on the first screen"
    if ver and pri:
        gap = pri["x"] - (ver["x"] + ver["w"])
        cy = abs((ver["y"] + ver["h"] / 2) - (pri["y"] + pri["h"] / 2))
        row = [l for l in leaves if abs((l["y"] + l["h"] / 2) - (pri["y"] + pri["h"] / 2)) < 10 and l["x"] > pri["x"]]
        right = W - (pri["x"] + pri["w"])
        g1 = 0 <= gap <= 12 and cy < 3 and pri["y"] + pri["h"] <= 100 and right <= 24 and not row
        why = (f"Print ends {right:.0f} px from the right edge and {pri['y'] + pri['h']:.0f} px from the top; "
               f"Verify sits {gap:.0f} px to its left on the same row"
               + ("" if not row else f"; but {', '.join(r['c'] for r in row)} is right of Print"))
    res["g1"] = (g1, why)
    # the marker on a phone: how much of it the chrome covers
    sp = facts["stages"][v["phone"]]
    mk = sp["marker"]
    pl, pb, _ = chrome_of(M["phone"])
    cov = sum(inter(mk, r) for r in pb + [l for l in pl if not any(inter(l, bx) >= l["w"] * l["h"] - 1 for bx in pb)])
    res["phone_marker_covered_pct"] = round(100 * min(1.0, cov / (mk["w"] * mk["h"])), 1)
    return res


def box_map(M: dict, facts: dict, v: dict) -> str:
    """The measured layout skeleton: every chrome box and control, coloured by role."""
    def one(st: str, scale: float) -> str:
        m = M[st]
        W, H = m["W"] * scale, m["H"] * scale
        leaves, boxes, panel = chrome_of(m)
        stage = next((b for b in m["boxes"] if b["box"] == "stage"), None)
        r = lambda o: f'x="{o["x"] * scale:.1f}" y="{o["y"] * scale:.1f}" width="{o["w"] * scale:.1f}" height="{o["h"] * scale:.1f}"'
        parts = [f'<rect x="0" y="0" width="{W:.1f}" height="{H:.1f}" fill="#f3f4f6" stroke="#9aa3ad"/>']
        if stage:
            parts.append(f'<rect {r(stage)} fill="#e9ecf0"/>')
        if panel:
            parts.append(f'<rect {r(panel)} fill="#ffffff" stroke="#c4cad2" stroke-dasharray="3 2"/>'
                         f'<text x="{(panel["x"] + panel["w"] / 2) * scale:.1f}" y="{(panel["y"] + panel["h"] / 2) * scale:.1f}" '
                         f'font-size="9" text-anchor="middle" fill="#8d96a3" font-family="system-ui">panel</text>')
        for b in boxes:
            parts.append(f'<rect {r(b)} fill="#ffffff" stroke="#c4cad2" rx="2"/>')
        for l in leaves:
            parts.append(f'<rect {r(l)} fill="{ROLE_COLOUR[role_of(l["c"])]}" opacity=".85" rx="1.5"><title>{E(l["c"])}</title></rect>')
        return f'<svg viewBox="0 0 {W:.1f} {H:.1f}" width="{W:.0f}" height="{H:.0f}" role="img" aria-label="{E(v["name"])} layout at {m["W"]:.0f}">{"".join(parts)}</svg>'
    legend = "".join(f'<span><i style="background:{ROLE_COLOUR[k]}"></i>{E(n)}</span>' for k, n in ROLE_NAME.items())
    return f'<div class="lp-map">{one("desk", 0.25)}{one("phone", 0.25)}</div><div class="lp-legend">{legend}</div>'


