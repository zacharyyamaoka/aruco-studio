def I(name: str, size: int = 16, cls: str = "") -> str:
    """An icon, the app's own glyph (16 grid) or lucide's (24 grid)."""
    st = f' style="width:{size}px;height:{size}px"'
    if name in LUCIDE:
        return (f'<svg class="lp-i {cls}" viewBox="0 0 24 24"{st} fill="none" stroke="currentColor" stroke-width="2" '
                f'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">{LUCIDE[name]}</svg>')
    vb = "0 0 64 64" if name == "brand" else "0 0 16 16"
    return f'<svg class="lp-i {cls}" viewBox="{vb}"{st} aria-hidden="true">{GLYPH[name]}</svg>'


