def A(c=None, to=None, show=None, press=None, title=None, box=None) -> str:
    a = ""
    if c:
        a += f' data-c="{c}"'
    if box:
        a += f' data-box="{box}"'
    if to:
        a += f' data-story-to="{to}" role="button" tabindex="0"'
    if show:
        a += f' data-show="{show}"'
    if press:
        a += f' data-press="{press}"'
    if title:
        a += f' title="{E(title)}"'
    return a


def kbd(k: str, cls: str = "") -> str:
    return f'<span class="lp-kbd {cls}">{E(k)}</span>'


def tip(name: str, key: str | None, up: bool = False) -> str:
    k = f"<b>{E(key)}</b>" if key else ""
    return f'<span class="lp-tt{" up" if up else ""}">{E(name)}{k}</span>'


def ib(icon: str, c=None, cls="", to=None, press=None, name=None, key=None, up=False, size=16, title=None) -> str:
    """An icon button; a name gives it the hover tooltip (name and key)."""
    live = " lp-live" if to else ""
    hov = " lp-hov" if name else ""
    t = tip(name, key, up) if name else ""
    return f'<span class="lp-ib {cls}{live}{hov}"{A(c, to, press=press, title=title)}>{I(icon, size)}{t}</span>'


